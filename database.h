#pragma once
// Модуль работы с базой данных (СУБД SQLite, драйвер QSQLITE).
// Здесь собрано всё, что не относится к интерфейсу: подключение, создание таблиц,
// тестовые данные, «макрос» пересчёта стоимости и тексты запросов.

#include <QSqlQuery>
#include <QString>

namespace Db {

// Подключение к файлу БД (создаётся автоматически, если его нет).
bool open(const QString &path, QString *error = nullptr);

// Создание таблиц ОТДЕЛЫ, СОТРУДНИКИ, КОМАНДИРОВКИ (если ещё не созданы).
bool createSchema(QString *error = nullptr);

// Заполнение тестовыми данными, если таблицы пустые.
bool seedIfEmpty(QString *error = nullptr);

// Полная очистка таблиц и повторное заполнение тестовыми данными.
bool resetDemoData(QString *error = nullptr);

// «Макрос»: пересчёт общей стоимости всех командировок
// по формуле: количество дней * суточные + 2 * стоимость дороги.
// Возвращает число обработанных записей (-1 при ошибке).
int recalcTotals(QString *error = nullptr);

// Общая стоимость одной командировки (та же формула, что и в макросе).
int tripTotal(int days, int allowance, int roadCost);

// Запрос 3: сотрудники, отправленные в командировку в заданный город (по заданию – Москва).
QSqlQuery tripsByCityQuery(const QString &city);

// Запрос 4: перекрёстный запрос – общая стоимость командировок;
// строки – сотрудники, столбцы – города, последний столбец – итог по сотруднику.
QSqlQuery crossTabQuery();

// Запрос 5: запрос с параметром – командировки сотрудника по введённому ФИО.
QSqlQuery tripsByFioQuery(const QString &fio);

// Приведение введённого пользователем текста к виду «Иванов И И»:
// в SQLite оператор LIKE не различает регистр только для латиницы,
// поэтому первую букву каждого слова делаем заглавной, остальные – строчными.
QStringList normalizeFioTokens(const QString &text);

} // namespace Db
